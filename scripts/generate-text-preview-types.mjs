#!/usr/bin/env node
// Regenerates packages/core/attachments/text-preview-types.ts from
// server/internal/handler/text_preview_types.json (the single source of truth).
//
// Run via `pnpm generate:text-preview-types`. CI re-runs the generator and
// `git diff --exit-code`s the output, so the JSON and TS sides cannot drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "server/internal/handler/text_preview_types.json");
const tsPath = resolve(repoRoot, "packages/core/attachments/text-preview-types.ts");

const raw = readFileSync(jsonPath, "utf8");
const data = JSON.parse(raw);

if (!Array.isArray(data.extensions) || !Array.isArray(data.contentTypes) || !Array.isArray(data.basenames)) {
  throw new Error(`text_preview_types.json: expected top-level arrays "extensions", "contentTypes", and "basenames"`);
}

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generate-text-preview-types.mjs.");
lines.push("// Do not edit by hand — edit server/internal/handler/text_preview_types.json");
lines.push("// and run `pnpm generate:text-preview-types`.");
lines.push("");
lines.push("/**");
lines.push(" * Text preview allowed types.");
lines.push(" *");
lines.push(" * Single source of truth: `server/internal/handler/text_preview_types.json`.");
lines.push(" * The Go backend embeds that JSON; this file is regenerated from it.");
lines.push(" * IMPORTANT — KEEP IN SYNC with isTextPreviewable() in server/internal/handler/file.go.");
lines.push(" */");

function addSet(name, arr) {
  lines.push(`export const ${name}: ReadonlySet<string> = new Set<string>([`);

  // Format elements nicely
  let currentLine = " ";
  for (let i = 0; i < arr.length; i++) {
    const val = JSON.stringify(arr[i]) + ",";
    if (currentLine.length + val.length > 70) {
      lines.push(currentLine);
      currentLine = "  " + val;
    } else {
      currentLine += (currentLine === " " ? " " : " ") + val;
    }
  }
  if (currentLine !== " ") {
    lines.push(currentLine);
  }

  lines.push("]);");
  lines.push("");
}

addSet("TEXT_EXTENSIONS", data.extensions);
addSet("TEXT_CONTENT_TYPES", data.contentTypes);
addSet("TEXT_BASENAMES", data.basenames);

writeFileSync(tsPath, lines.join("\n"));
